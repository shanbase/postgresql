// Data-directory preparation: SSL certificate generation, initdb on first
// boot, postgresql.conf + pg_hba.conf generation, and ownership fixes so the
// postgres server can run as a non-root OS user.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { run, fileExists, asPgUser, chownToPgUser, ensureOsUser, which, pgEnv } from './procs.mjs';
import { prepareInitdbEnvironment } from './uidCompat.mjs';

const q = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

/** Resolve the server certificate + key: custom pair wins, else self-signed. */
export async function ensureCerts(cfg, log) {
  // Custom certificate pair (PG_SSL_CERT_FILE / PG_SSL_KEY_FILE) overrides
  // auto-generation entirely.
  if (cfg.sslCertFile || cfg.sslKeyFile) {
    if (!cfg.sslCertFile || !cfg.sslKeyFile) {
      throw new Error('PG_SSL_CERT_FILE and PG_SSL_KEY_FILE must be set together.');
    }
    if (!fileExists(cfg.sslCertFile)) throw new Error(`PG_SSL_CERT_FILE not found: ${cfg.sslCertFile}`);
    if (!fileExists(cfg.sslKeyFile)) throw new Error(`PG_SSL_KEY_FILE not found: ${cfg.sslKeyFile}`);
    try { fs.chmodSync(cfg.sslKeyFile, 0o600); } catch { /* windows */ }
    await chownToPgUser(cfg, cfg.sslCertFile, log);
    await chownToPgUser(cfg, cfg.sslKeyFile, log);
    log.info('ssl', `using custom certificate ${cfg.sslCertFile} / ${cfg.sslKeyFile}`);
    return { certFile: cfg.sslCertFile, keyFile: cfg.sslKeyFile };
  }

  const certDir = path.join(cfg.dataDir, 'certs');
  const certFile = path.join(certDir, 'server.crt');
  const keyFile = path.join(certDir, 'server.key');
  fs.mkdirSync(certDir, { recursive: true });

  if (fileExists(certFile) && fileExists(keyFile)) {
    log.info('ssl', `reusing existing certificate ${certFile}`);
    return { certFile, keyFile };
  }

  const openssl = which('openssl');
  if (!openssl) throw new Error('PG_SSL=on but the openssl binary was not found.');

  const cn = cfg.sslCn || os.hostname() || 'localhost';
  log.info('ssl', `generating self-signed certificate (CN=${cn}, ${cfg.sslDays} days)`);
  const subj = `/CN=${cn.replace(/[^\w.\-]/g, '')}`;
  const san = `subjectAltName=DNS:${cn},DNS:localhost,IP:127.0.0.1,IP:::1`;
  const tmpKey = `${keyFile}.tmp`;
  const tmpCrt = `${certFile}.tmp`;

  await run(openssl, [
    'req', '-x509', '-newkey', 'rsa:2048', '-sha256', '-nodes',
    '-keyout', tmpKey, '-out', tmpCrt,
    '-days', String(cfg.sslDays),
    '-subj', subj, '-addext', san,
  ], { log, tag: 'openssl' });

  fs.renameSync(tmpKey, keyFile);
  fs.renameSync(tmpCrt, certFile);
  try { fs.chmodSync(keyFile, 0o600); } catch { /* windows */ }
  try { fs.chmodSync(certFile, 0o644); } catch { /* windows */ }
  log.info('ssl', `certificate written to ${certFile}`);
  return { certFile, keyFile };
}

/** Render postgresql.conf from config. */
export function renderPostgresqlConf(cfg, certFile, keyFile) {
  const lines = [
    '# Generated by veyra-postgres — edit .env and restart instead of editing this file.',
    `listen_addresses = ${q(cfg.listen)}`,
    `port = ${cfg.port}`,
    `unix_socket_directories = ${q(cfg.socketDir)}`,
    `max_connections = ${cfg.maxConnections}`,
    `shared_buffers = ${q(cfg.sharedBuffers)}`,
    `effective_cache_size = ${q(cfg.effectiveCacheSize)}`,
    `work_mem = ${q(cfg.workMem)}`,
    `maintenance_work_mem = ${q(cfg.maintenanceWorkMem)}`,
    `max_wal_size = ${q(cfg.maxWalSize)}`,
    `password_encryption = 'scram-sha-256'`,
    `ssl_min_protocol_version = ${q(cfg.sslMinVersion)}`,
    `log_timezone = 'UTC'`,
    `datestyle = 'iso, mdy'`,
    `log_connections = on`,
    `log_disconnections = on`,
    `log_line_prefix = '%m [%p] %u@%d %a '`,
    `logging_collector = off`,
  ];
  if (cfg.ssl === 'on' && certFile) {
    lines.push(`ssl = on`, `ssl_cert_file = ${q(certFile)}`, `ssl_key_file = ${q(keyFile)}`);
  } else {
    lines.push(`ssl = off`);
  }
  return lines.join('\n') + '\n';
}

/** Render pg_hba.conf: local peer for the postgres OS user, scram-sha-256 everywhere else. */
export function renderPgHba(cfg) {
  const lines = [
    '# Generated by veyra-postgres',
    '# TYPE  DATABASE  USER  ADDRESS           METHOD',
    `local   all       postgres               peer`,
    `local   all       all                    scram-sha-256`,
    `host    all       all      127.0.0.1/32    scram-sha-256`,
    `host    all       all      ::1/128         scram-sha-256`,
  ];
  for (const cidr of cfg.allowedCidrs) {
    lines.push(`host    all       all      ${cidr.padEnd(18)} scram-sha-256`);
  }
  lines.push(`host    all       all      all              reject`);
  return lines.join('\n') + '\n';
}

function bin(cfg, pg, name) {
  return path.join(pg.binDir, process.platform === 'win32' ? `${name}.exe` : name);
}

/**
 * Ensure the data directory is initialized and configured.
 * Returns { certFile, keyFile } when SSL is enabled.
 */
export async function prepareDatabase(cfg, pg, password, log) {
  await ensureOsUser(cfg, log);
  fs.mkdirSync(cfg.dataDir, { recursive: true });
  await chownToPgUser(cfg, cfg.dataDir, log);

  const versionFile = path.join(cfg.dataDir, 'PG_VERSION');
  const fresh = !fileExists(versionFile);

  if (fresh) {
    const legacyCompatDir = path.join(cfg.dataDir, '.compat');
    const legacyPasswordFile = path.join(cfg.dataDir, '.initdb-pw');
    if (fs.existsSync(legacyCompatDir) || fs.existsSync(legacyPasswordFile)) {
      log.warn('initdb', 'removing temporary bootstrap files left by version 1.0.1');
      fs.rmSync(legacyCompatDir, { recursive: true, force: true });
      fs.rmSync(legacyPasswordFile, { force: true });
    }

    const remaining = fs.readdirSync(cfg.dataDir);
    if (remaining.length > 0) {
      throw new Error(
        `PG_DATA directory is not empty: ${cfg.dataDir} (contains: ${remaining.slice(0, 8).join(', ')}). ` +
        'Move unrelated files elsewhere or set PG_DATA to an empty subdirectory such as ./data/pgdata.',
      );
    }

    log.info('initdb', `initializing data directory at ${cfg.dataDir}`);
    const bootstrapDir = fs.mkdtempSync(path.join(os.tmpdir(), 'veyra-postgres-initdb-'));
    const pwFile = path.join(bootstrapDir, 'initdb-password');
    let identity;
    try {
      fs.writeFileSync(pwFile, password + '\n', { mode: 0o600 });
      await chownToPgUser(cfg, bootstrapDir, log);
      identity = await prepareInitdbEnvironment(cfg, pg, log, bootstrapDir);
      const args = asPgUser(cfg, bin(cfg, pg, 'initdb'), [
        '-D', cfg.dataDir,
        '-U', cfg.superuser,
        '--auth=scram-sha-256',
        '--pwfile=' + pwFile,
        '-E', 'UTF8',
        '--locale=C',
        '--no-instructions',
      ]);
      await run(args[0], args.slice(1), { log, tag: 'initdb', env: identity.env, timeoutMs: 10 * 60 * 1000 });
    } finally {
      identity?.cleanup();
      fs.rmSync(bootstrapDir, { recursive: true, force: true });
    }
  } else {
    log.info('initdb', `data directory already initialized (${cfg.dataDir})`);
  }

  // Certificates (before config so paths can be referenced).
  let certFile = null, keyFile = null;
  if (cfg.ssl === 'on') {
    ({ certFile, keyFile } = await ensureCerts(cfg, log));
  }

  const confPath = path.join(cfg.dataDir, 'postgresql.conf');
  fs.writeFileSync(confPath, renderPostgresqlConf(cfg, certFile, keyFile));
  fs.writeFileSync(path.join(cfg.dataDir, 'pg_hba.conf'), renderPgHba(cfg));
  log.info('config', `wrote ${confPath} and pg_hba.conf (ssl=${cfg.ssl}, port=${cfg.port})`);

  await chownToPgUser(cfg, cfg.dataDir, log);
  return { certFile, keyFile };
}

/** Run a one-off SQL statement as the pg OS user over the unix socket (peer auth). */
export async function sqlAsPgUser(cfg, pg, sql, log) {
  const psql = bin(cfg, pg, 'psql');
  const args = asPgUser(cfg, psql, [
    '-h', cfg.socketDir, '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-c', sql,
  ]);
  await run(args[0], args.slice(1), { log, tag: 'psql', env: pgEnv(pg), timeoutMs: 60 * 1000 });
}
