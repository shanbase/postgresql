// veyra-postgres — self-contained PostgreSQL bootstrapper for generic
// Node.js 22 hosts (e.g. Altare). Installs Postgres if missing, generates
// SSL certs, writes hardened config, supervises the server, logs everything.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { loadConfig } from './lib/config.mjs';
import { createLogger } from './lib/logger.mjs';
import { ensurePostgres } from './lib/install.mjs';
import { prepareDatabase } from './lib/setup.mjs';
import { PostgresSupervisor } from './lib/postgres.mjs';
import { prepareNativeLibs } from './lib/nativeLibs.mjs';
import { startHealthServer } from './lib/health.mjs';

const cfg = loadConfig();
const log = createLogger({ level: process.env.LOG_LEVEL || 'info', logDir: path.join(cfg.root, 'logs') });

function banner() {
  log.info('boot', '════════════════════════════════════════════════════════════');
  log.info('boot', '  veyra-postgres — self-contained PostgreSQL supervisor');
  log.info('boot', '════════════════════════════════════════════════════════════');
  log.info('config', `port=${cfg.port} user=${cfg.superuser} db(s)=${cfg.databases.join(',')}`);
  log.info('config', `listen=${cfg.listen} ssl=${cfg.ssl} allowed=${cfg.allowedCidrs.join(',')}`);
  log.info('config', `data=${cfg.dataDir} shared_buffers=${cfg.sharedBuffers} work_mem=${cfg.workMem} max_connections=${cfg.maxConnections}`);
  log.info('config', `health_port=${cfg.healthPort || 'disabled'}`);
}

/** Ensure a password exists; generate + persist one when unset. */
function resolvePassword() {
  if (cfg.password) return { password: cfg.password, generated: false };
  const password = crypto.randomBytes(24).toString('base64url');
  const credFile = path.join(cfg.root, '.pg-credentials');
  try {
    fs.writeFileSync(credFile,
      `# Generated by veyra-postgres on first boot. Keep secret.\n` +
      `PG_SUPERUSER=${cfg.superuser}\nPG_PASSWORD=${password}\n` +
      `PG_PORT=${cfg.port}\nPG_DATABASE=${cfg.databases.join(',')}\n`,
      { mode: 0o600 });
  } catch (err) {
    log.warn('auth', `could not write ${credFile}: ${err.message}`);
  }
  return { password, generated: true, credFile };
}

async function main() {
  banner();

  const { password, generated, credFile } = resolvePassword();
  if (generated) {
    log.warn('auth', 'PG_PASSWORD was empty — generated a random superuser password:');
    log.warn('auth', `  password: ${password}`);
    log.warn('auth', `  saved to: ${credFile || '(not saved)'}  — set PG_PASSWORD in .env to choose your own`);
  }

  const pg = await ensurePostgres(cfg, log);
  pg.libDir = prepareNativeLibs(pg.binDir, log);
  await prepareDatabase(cfg, pg, password, log);

  const supervisor = new PostgresSupervisor(cfg, pg, log);
  const health = startHealthServer(cfg, pg, supervisor, log);

  supervisor.launch();
  const ready = await supervisor.waitReady();
  if (ready) {
    await supervisor.ensureDatabases(password, log);
    log.info('boot', `PostgreSQL is up — postgresql://${cfg.superuser}:***@<host>:${cfg.port}/`);
    if (cfg.ssl === 'on') log.info('boot', 'TLS enabled (self-signed cert — use sslmode=require or provide your own CA)');
  } else {
    log.error('boot', 'PostgreSQL did not become ready; supervisor will keep retrying. Check logs above.');
  }

  let shuttingDown = false;
  const shutdown = async (sig) => {
    if (shuttingDown) return;
    shuttingDown = true;
    log.info('boot', `received ${sig} — shutting down`);
    health?.close();
    await supervisor.stop();
    log.close();
    process.exit(0);
  };
  process.on('SIGINT', () => shutdown('SIGINT'));
  process.on('SIGTERM', () => shutdown('SIGTERM'));
  process.on('uncaughtException', (err) => {
    log.error('fatal', err);
    process.exit(1);
  });
  process.on('unhandledRejection', (err) => {
    log.error('fatal', err instanceof Error ? err : new Error(String(err)));
  });
}

main().catch((err) => {
  console.error('[fatal]', err);
  process.exit(1);
});
